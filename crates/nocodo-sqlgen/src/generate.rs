//! `generate`: turn a change set into `up.sql` / `down.sql`. Pure.
//!
//! SQL comes from the change list, not from a spec diff, so renames stay renames.

use nocodo_types::change::{ChangeSet, SchemaChange};
use nocodo_types::schema::{Column, ColumnType, SchemaSpec, Table};

use crate::apply::{ApplyError, apply_one};
use crate::naming::{IndexDef, column_sql_type, table_indexes};

/// Content of `metadata.toml` next to every `up.sql`/`down.sql`. The SQL
/// manages its own transaction because Diesel cannot change `foreign_keys`
/// inside one.
pub const METADATA_TOML: &str = "run_in_transaction = false\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Migration {
    pub up: String,
    pub down: String,
}

const TIMESTAMP_DEFAULT: &str = "TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))";

/// Generate the migration for `change_set`, applied on top of `before`.
pub fn generate(before: &SchemaSpec, change_set: &ChangeSet) -> Result<Migration, ApplyError> {
    let mut ups: Vec<String> = Vec::new();
    let mut downs: Vec<String> = Vec::new();
    let mut cur = before.clone();
    for change in &change_set.changes {
        let next = apply_one(&cur, change)?;
        ups.push(up_block(&cur, &next, change));
        downs.push(down_block(&cur, &next, change));
        cur = next;
    }
    downs.reverse();

    let name = &change_set.name;
    let header =
        format!("-- Generated by nocodo-sqlgen from change set \"{name}\". Do not edit.\n");
    let down_note = "-- Restores the structure from before this change set. Columns and tables that\n\
                     -- were dropped by it come back empty; their data is not recovered.\n";
    Ok(Migration {
        up: wrap(&header, &ups),
        down: wrap(&format!("{header}{down_note}"), &downs),
    })
}

fn wrap(header: &str, blocks: &[String]) -> String {
    let mut s = String::from(header);
    s.push_str("PRAGMA foreign_keys = OFF;\nBEGIN;\n");
    for b in blocks {
        s.push('\n');
        s.push_str(b);
    }
    s.push_str("\nCOMMIT;\nPRAGMA foreign_keys = ON;\n");
    s
}

fn find<'a>(spec: &'a SchemaSpec, name: &str) -> &'a Table {
    spec.tables
        .iter()
        .find(|t| t.name == name)
        .expect("table exists: apply_one succeeded")
}

fn up_block(before: &SchemaSpec, after: &SchemaSpec, change: &SchemaChange) -> String {
    match change {
        SchemaChange::CreateTable { table, .. } => {
            let t = find(after, table);
            format!("-- Create table {table}\n{}", create_table_with_indexes(t))
        }
        SchemaChange::AddColumn { table, column } => {
            let mut s = format!(
                "-- Add column {table}.{}\nALTER TABLE {table} ADD COLUMN {};\n",
                column.name,
                column_def(column)
            );
            if column.unique {
                let idx = table_indexes(find(after, table))
                    .into_iter()
                    .find(|d| d.unique && d.columns == [column.name.clone()])
                    .expect("unique column has an index");
                s.push_str(&create_index(table, &idx));
            }
            s
        }
        SchemaChange::AddIndex { table, .. } => {
            let idx = table_indexes(find(after, table))
                .pop() // AddIndex appends: the explicit index is last
                .expect("index exists after apply");
            format!("-- Add index {}\n{}", idx.name, create_index(table, &idx))
        }
        SchemaChange::AddForeignKey {
            table,
            column,
            references,
        } => format!(
            "-- Add foreign key {table}.{column} -> {references}(id) (table rebuild)\n{}",
            rebuild(find(before, table), find(after, table))
        ),
        SchemaChange::RenameTable { from, to } => format!(
            "-- Rename table {from} to {to}\n{}",
            rename_table(find(before, from), find(after, to))
        ),
        SchemaChange::RenameColumn { table, from, to } => format!(
            "-- Rename column {table}.{from} to {to}\n{}",
            rename_column(find(before, table), find(after, table), from, to)
        ),
        SchemaChange::DropColumn { table, column } => format!(
            "-- Drop column {table}.{column} (table rebuild)\n{}",
            rebuild(find(before, table), find(after, table))
        ),
        SchemaChange::DropTable { table } => {
            format!("-- Drop table {table}\nDROP TABLE {table};\n")
        }
    }
}

fn down_block(before: &SchemaSpec, after: &SchemaSpec, change: &SchemaChange) -> String {
    match change {
        SchemaChange::CreateTable { table, .. } => {
            format!("-- Undo: create table {table}\nDROP TABLE {table};\n")
        }
        SchemaChange::AddColumn { table, column } => format!(
            "-- Undo: add column {table}.{} (table rebuild)\n{}",
            column.name,
            rebuild(find(after, table), find(before, table))
        ),
        SchemaChange::AddIndex { table, .. } => {
            let idx = table_indexes(find(after, table))
                .pop() // AddIndex appends: the explicit index is last
                .expect("index exists after apply");
            format!(
                "-- Undo: add index {}\nDROP INDEX {};\n",
                idx.name, idx.name
            )
        }
        SchemaChange::AddForeignKey { table, column, .. } => format!(
            "-- Undo: add foreign key {table}.{column} (table rebuild)\n{}",
            rebuild(find(after, table), find(before, table))
        ),
        SchemaChange::RenameTable { from, to } => format!(
            "-- Undo: rename table {from} to {to}\n{}",
            rename_table(find(after, to), find(before, from))
        ),
        SchemaChange::RenameColumn { table, from, to } => format!(
            "-- Undo: rename column {table}.{from} to {to}\n{}",
            rename_column(find(after, table), find(before, table), to, from)
        ),
        SchemaChange::DropColumn { table, column } => format!(
            "-- Undo: drop column {table}.{column} (table rebuild; column comes back empty)\n{}",
            rebuild(find(after, table), find(before, table))
        ),
        SchemaChange::DropTable { table } => format!(
            "-- Undo: drop table {table} (table comes back empty)\n{}",
            create_table_with_indexes(find(before, table))
        ),
    }
}

fn column_def(c: &Column) -> String {
    let mut s = format!("{} {}", c.name, column_sql_type(c.column_type));
    if !c.nullable {
        s.push_str(" NOT NULL");
    }
    if c.column_type == ColumnType::Boolean {
        s.push_str(&format!(" CHECK ({} IN (0, 1))", c.name));
    }
    if let Some(r) = &c.references {
        s.push_str(&format!(" REFERENCES {r}(id)"));
    }
    s
}

fn create_table(name: &str, t: &Table) -> String {
    let mut lines = vec!["    id INTEGER PRIMARY KEY".to_string()];
    lines.extend(t.columns.iter().map(|c| format!("    {}", column_def(c))));
    lines.push(format!("    created_at {TIMESTAMP_DEFAULT}"));
    lines.push(format!("    updated_at {TIMESTAMP_DEFAULT}"));
    format!("CREATE TABLE {name} (\n{}\n);\n", lines.join(",\n"))
}

fn create_index(table: &str, d: &IndexDef) -> String {
    let unique = if d.unique { "UNIQUE " } else { "" };
    format!(
        "CREATE {unique}INDEX {} ON {table} ({});\n",
        d.name,
        d.columns.join(", ")
    )
}

fn create_table_with_indexes(t: &Table) -> String {
    let mut s = create_table(&t.name, t);
    for d in table_indexes(t) {
        s.push_str(&create_index(&t.name, &d));
    }
    s
}

/// Value used to fill a column that does not exist in the source table.
fn empty_value(c: &Column) -> String {
    if c.nullable {
        return "NULL".into();
    }
    match (c.unique, c.column_type) {
        // Keep unique columns unique when restored for many rows.
        (true, ColumnType::Integer | ColumnType::Money) => "id".into(),
        (true, ColumnType::Text | ColumnType::Date | ColumnType::DateTime) => {
            "CAST(id AS TEXT)".into()
        }
        (_, ColumnType::Text | ColumnType::Date | ColumnType::DateTime) => "''".into(),
        (_, ColumnType::Integer | ColumnType::Money | ColumnType::Boolean) => "0".into(),
    }
}

/// SQLite's 12-step table rebuild, from the structure `from` to `to`
/// (same table name). Columns missing in `from` are filled with empty values.
fn rebuild(from: &Table, to: &Table) -> String {
    let name = &to.name;
    let mut targets = vec!["id".to_string()];
    let mut sources = vec!["id".to_string()];
    for c in &to.columns {
        targets.push(c.name.clone());
        sources.push(if from.columns.iter().any(|f| f.name == c.name) {
            c.name.clone()
        } else {
            empty_value(c)
        });
    }
    for ts in ["created_at", "updated_at"] {
        targets.push(ts.into());
        sources.push(ts.into());
    }
    let mut s = create_table(&format!("{name}_new"), to);
    s.push_str(&format!(
        "INSERT INTO {name}_new ({})\nSELECT {}\nFROM {name};\n",
        targets.join(", "),
        sources.join(", ")
    ));
    s.push_str(&format!(
        "DROP TABLE {name};\nALTER TABLE {name}_new RENAME TO {name};\n"
    ));
    for d in table_indexes(to) {
        s.push_str(&create_index(name, &d));
    }
    s
}

fn drop_indexes(indexes: &[IndexDef]) -> String {
    indexes
        .iter()
        .map(|d| format!("DROP INDEX {};\n", d.name))
        .collect()
}

/// Rename a table; indexes carry the table name, so they are recreated.
fn rename_table(from: &Table, to: &Table) -> String {
    let mut s = drop_indexes(&table_indexes(from));
    s.push_str(&format!(
        "ALTER TABLE {} RENAME TO {};\n",
        from.name, to.name
    ));
    for d in table_indexes(to) {
        s.push_str(&create_index(&to.name, &d));
    }
    s
}

/// Rename a column; indexes that contain it carry its name, so they are recreated.
fn rename_column(before: &Table, after: &Table, from: &str, to: &str) -> String {
    let touched = |d: &IndexDef, col: &str| d.columns.iter().any(|c| c == col);
    let old: Vec<IndexDef> = table_indexes(before)
        .into_iter()
        .filter(|d| touched(d, from))
        .collect();
    let mut s = drop_indexes(&old);
    s.push_str(&format!(
        "ALTER TABLE {} RENAME COLUMN {from} TO {to};\n",
        before.name
    ));
    for d in table_indexes(after).into_iter().filter(|d| touched(d, to)) {
        s.push_str(&create_index(&after.name, &d));
    }
    s
}
